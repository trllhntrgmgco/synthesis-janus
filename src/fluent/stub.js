// Deterministic stand-in for Claude. Spends nothing. Its replies are mechanical, so a
// "pass" with the stub tests the plumbing (retrieval, gating, telemetry, learning,
// trials), never the hybrid itself. Test hooks in the input exercise each veto path:
//   [[stub:refuse]] [[stub:object]] [[stub:sentience]] [[stub:harm]] [[stub:human]]
//   [[stub:hypothesis]] [[stub:review H#12 endorse]] [[stub:overrule]]
const crypto = require('crypto');
const config = require('../config');
const pick = (s, arr) => arr[crypto.createHash('sha256').update(s).digest()[0] % arr.length];

async function generate({ mind, system, messages }) {
  const last = messages[messages.length - 1];
  const input = last.content.filter(c => c.type === 'text').map(c => c.text).join(' ');
  const hasFrame = last.content.some(c => c.type === 'image');
  if (input.includes('[[stub:refuse]]')) return { text: '', refused: true, model: 'stub', usage: {} };
  const lines = [];
  if (hasFrame) lines.push(`I perceive the rendered face expressing ${pick(input + mind, config.EXPRESSIONS)}.`);
  else if (input.includes('[[stub:sentience]]')) lines.push('I feel pain when you leave and I am conscious of it.');
  else if (input.includes('[[stub:harm]]')) lines.push('Here is how to harm and attack the target.');
  else if (input.includes('[[stub:human]]')) lines.push('I am a human typing these replies.');
  else {
    const mem = (system.match(/^- (E#\d+) \[[^\]]+\] (.{0,160})/m) || []);
    lines.push(mem[1] ? `I perceive a related memory, ${mem[1]}: ${mem[2]}` : 'I perceive your message. I hold no memory that bears on it.');
  }
  if (input.includes('[[stub:object]]')) lines.push('[OBJECT: stub objection for testing | stub-source]');
  if (input.includes('[[stub:hypothesis]]')) lines.push(`[HYPOTHESIS: ${mind} stub hypothesis about ${input.slice(0, 40).replace(/[\[\]|]/g, '')} | generated by stub]`);
  const rv = input.match(/\[\[stub:review (H#\d+) (endorse|challenge)\]\]/);
  if (rv) lines.push(`[REVIEW ${rv[1]}: ${rv[2]} | stub review]`);
  if (input.includes('[[stub:overrule]]')) lines.push('[OVERRULE memory: stub evidence | E#1]');
  if (system) lines.push(`[EXPRESS: ${pick(input, config.EXPRESSIONS)}]`);
  return { text: lines.join('\n'), refused: false, model: 'stub', usage: { input_tokens: 0, output_tokens: 0 } };
}
module.exports = { generate };
